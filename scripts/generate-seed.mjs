// Generates data/seed-words.json (demo mode) and supabase/seed.sql from supabase/seed/words.txt
import fs from "node:fs";

const CATS = [
  ["stops", "עוצרים (פלוסיבים)", "צלילים שנוצרים כשהאוויר נעצר לרגע ונפלט בבת אחת — למשל /פ/, /ב/, /ט/, /ד/, /ק/, /ג/."],
  ["fricatives", "חוככים (פריקטיבים)", "צלילים שנוצרים מחיכוך של אוויר רצוף במעבר צר — למשל /ש/, /ס/, /ז/, /ח/, /ה/."],
  ["affricates", "אפריקטים", "צלילים משולבים: עצירה שמשתחררת לחיכוך — למשל /צ/ ו-/ג׳/."],
  ["nasals", "נזליים", "צלילים שהאוויר עובר בהם דרך האף — /מ/ ו-/נ/."],
  ["liquids", "נוזליים", "צלילים זורמים ו\"גליליים\" שקשים לרכישה — /ל/ ו-/ר/."],
  ["glides", "גלישים ותחילת תנועה", "מילים שמתחילות בתנועה או בגלישה — /י/, /א/, /ע/."],
];
const FIRST = {
  ב: "stops", פ: "stops", ט: "stops", ת: "stops", ד: "stops", ק: "stops", כ: "stops", ג: "stops",
  ש: "fricatives", ס: "fricatives", ז: "fricatives", ח: "fricatives", ה: "fricatives", ו: "fricatives",
  צ: "affricates", מ: "nasals", נ: "nasals", ל: "liquids", ר: "liquids", י: "glides", א: "glides", ע: "glides",
};
const FINAL = { ך: "כ", ם: "מ", ן: "נ", ף: "פ", ץ: "צ" };
const strip = (s) => s.replace(/[֑-ׇ]/g, "").replace(/׳/g, "");
const norm = (c) => FINAL[c] ?? c;
const DIFF = { e: "easy", m: "medium", h: "hard" };

const words = fs
  .readFileSync("supabase/seed/words.txt", "utf8")
  .split("\n")
  .filter((l) => l.trim() && !l.startsWith("#"))
  .map((line, i) => {
    const [text, syl, vowels, age, diff, abs, emoji] = line.split("|");
    const plain = strip(text);
    const [age_min, age_max] = age.split("-").map(Number);
    const kinds = ["illustration"];
    if (i % 2 === 0) kinds.push("color");
    if (i % 3 === 0) kinds.push("bw");
    return {
      slug: `seed-${String(i + 1).padStart(3, "0")}`,
      text, plain_text: plain, syllable_count: Number(syl),
      letter_count: [...plain].length, vowels: vowels.split(","),
      primary_phoneme: norm(plain[0]), category: text.includes("ג׳") && plain[0] === "ג" ? "affricates" : FIRST[norm(plain[0])],
      age_min, age_max, difficulty: DIFF[diff], abstractness: abs === "a" ? "abstract" : "concrete",
      emoji, image_kinds: kinds, cultural_warning: false,
    };
  });

for (const w of words) if (!w.category) throw new Error("no category for " + w.text);
fs.writeFileSync("data/seed-words.json", JSON.stringify({ categories: CATS.map(([slug, name_he, description_he]) => ({ slug, name_he, description_he })), words }, null, 1));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
let sql = "-- GENERATED by scripts/generate-seed.mjs — do not edit by hand\n";
sql += "insert into phonological_categories (slug, name_he, description_he) values\n";
sql += CATS.map(([s, n, d]) => `  (${q(s)}, ${q(n)}, ${q(d)})`).join(",\n") + "\non conflict (slug) do nothing;\n\n";
sql += "insert into words (text, syllable_count, vowels, primary_phoneme, category_id, age_min, age_max, difficulty, abstractness, emoji)\nselect v.text, v.syl::smallint, v.vowels, v.pp, c.id, v.amin::smallint, v.amax::smallint, v.diff::difficulty_level, v.abs::abstractness_level, v.emoji from (values\n";
sql += words.map((w) => `  (${q(w.text)}, ${w.syllable_count}, ${arr(w.vowels)}, ${q(w.primary_phoneme)}, ${q(w.category)}, ${w.age_min}, ${w.age_max}, ${q(w.difficulty)}, ${q(w.abstractness)}, ${q(w.emoji)})`).join(",\n");
sql += "\n) as v(text, syl, vowels, pp, cat, amin, amax, diff, abs, emoji)\njoin phonological_categories c on c.slug = v.cat\nwhere not exists (select 1 from words x where x.text = v.text);\n\n";
sql += "-- placeholder illustrations (emoji-based) so image-type filters work in the demo data\n";
sql += "insert into word_images (word_id, kind, url)\nselect w.id, k.kind::image_kind, null from words w join (values\n";
sql += words.flatMap((w) => w.image_kinds.map((k) => `  (${q(w.text)}, ${q(k)})`)).join(",\n");
sql += "\n) as k(text, kind) on k.text = w.text\nwhere not exists (select 1 from word_images i where i.word_id = w.id and i.kind = k.kind::image_kind);\n";
fs.writeFileSync("supabase/seed.sql", sql);
console.log(`generated ${words.length} words`);
